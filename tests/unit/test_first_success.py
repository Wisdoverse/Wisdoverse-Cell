def test_agent_http_option_reports_pending_without_faking_handoffs() -> None:
    class NoCalls:
        def get(self, *args: Any, **kwargs: Any) -> dict[str, Any]:
            raise AssertionError("pending agent workflow should not make API calls")

        def post(self, *args: Any, **kwargs: Any) -> dict[str, Any]:
            raise AssertionError("pending agent workflow should not make API calls")

    result = first_success.run_first_success(
        first_success.RunOptions(
            base_url="http://localhost:8000",
            company_id="cmp_demo",
            run_key="sample-report",
            checkpoint=Path("unused-checkpoint.json"),
            workflow="agent-http",
        ),
        NoCalls(),
    )

    assert result["status"] == "pending"
    assert [item["role"] for item in result["known_endpoints"]] == [
        "Requirement Manager",
        "Requirement Manager",
        "PJM",
        "Dev",
        "QA",
    ]
    assert "no stable HTTP handoff contract" in result["reason"]
    assert result["completion_claimed"] is False
    assert len(result["fixed_cases"]) == 4
    assert all(not row["configured"] for row in result["runtime_probes"])


def test_agent_http_probes_only_health_gets_and_never_claims_completion(monkeypatch: Any) -> None:
    requests: list[tuple[str, str]] = []

    class Response:
        status = 200

        def __enter__(self) -> Response:
            return self

        def __exit__(self, *args: Any) -> None:
            return None

        def read(self) -> bytes:
            return b'{"status":"ready"}'

    def fake_urlopen(request: Any, timeout: int) -> Response:
        requests.append((request.get_method(), request.full_url))
        return Response()

    monkeypatch.setattr(first_success, "urlopen", fake_urlopen)
    urls = {name: f"https://{name}.example" for name in first_success.RUNTIME_NAMES}
    result = first_success.agent_workflow_pending(
        "https://control.example", runtime_urls=urls, headers={"X-Internal-Key": "secret"}
    )

    assert len(requests) == 12
    assert all(method == "GET" for method, _ in requests)
    assert all(any(path in url for path in ("/health",)) for _, url in requests)
    assert result["status"] == "pending"
    assert result["completion_claimed"] is False
    assert all(
        all(probe["ok"] for probe in runtime["probes"].values())
        for runtime in result["runtime_probes"]
    )
    assert "secret" not in json.dumps(result)


def test_auth_headers_are_read_from_environment_without_echoing_them() -> None:
    headers = first_success.headers_from_environment(
        {
            "INTERNAL_SERVICE_KEY": "internal-secret-value",
            "CONTROL_PLANE_OPERATOR_TOKEN": "operator-secret-value",
        }
    )

    assert headers == {
        "X-Internal-Key": "internal-secret-value",
        "X-Control-Plane-Operator-Token": "operator-secret-value",
    }
    assert "internal-secret-value" not in json.dumps(
        first_success.agent_workflow_pending("https://cell.example")
    )
